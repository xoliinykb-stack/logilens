class _Safe(dict[str, Any]):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def tr(key: str, lang: str, **params: Any) -> str:
    """TUI string, falling back to the shared catalogs (:func:`logilens.i18n.t`)."""
    lang = normalize_lang(lang)
    for catalog in (STRINGS[lang], STRINGS["en"]):
        if key in catalog:
            text = catalog[key]
            if not params:
                return text
            try:
                return text.format_map(_Safe(params))
            except (ValueError, IndexError, AttributeError):
                return text
    return t(key, lang, **params)


